from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from typing import TYPE_CHECKING, Any, Self

from hare import fields
from hare.contrib.outbox.constants import OUTBOX_KEY_MAX_LENGTH, OUTBOX_WAKEUP_META_OPTION
from hare.contrib.outbox.outbox_enqueue import OutboxEnqueue
from hare.contrib.outbox.outbox_idempotency import OutboxIdempotency
from hare.contrib.outbox.outbox_json_encoding import OutboxJsonEncoding
from hare.contrib.outbox.outbox_validation import OutboxValidation
from hare.contrib.outbox.outbox_wakeups import OutboxWakeups
from hare.ddl.indexes.index import Index
from hare.ddl.indexes.partial_index import PartialIndex
from hare.dialects.base.client.database_client import DatabaseClient
from hare.fields.data.json.json_text_field import JSONTextField
from hare.fields.uuid7 import Uuid7
from hare.models import Model
from hare.models.class_building.extension_model_options import ExtensionModelOptions
from hare.query.expressions import Q

if TYPE_CHECKING:
    from hare.contrib.outbox.outbox_message import OutboxMessage
    from hare.contrib.outbox.wakeups.outbox_wakeup import OutboxWakeup


ExtensionModelOptions.allow(OUTBOX_WAKEUP_META_OPTION)


class OutboxEvent(Model):
    """A transactional outbox row: written by ``enqueue()`` - or by ``Meta.change_capture`` of a
    captured model - in the transaction of the change it reports, and delivered afterwards by an
    ``OutboxRelay``.

    Combine with your own project's base model through multiple inheritance:

    Example:
        class MyOutboxEvent(YourBaseModel, OutboxEvent):
            class Meta(YourBaseModel.Meta, OutboxEvent.Meta):
                outbox_wakeup = ListenNotifyWakeup()

    ``Meta.outbox_wakeup`` is the wakeup the events of the model signal once their transaction
    commits - the relay subscribes to it; none to rely on the relay's polling.

    ``OutboxEvent.Meta`` declares only ``abstract = True`` and the relay's own ``indexes`` on
    purpose - ``ModelMeta`` merges every abstract ancestor's ``Meta`` attributes via a reversed-MRO
    walk, and lets whichever ancestor comes later in that walk win on a key collision. Adding
    anything else to this Meta (a ``table`` name, ...) would risk colliding with
    ``YourBaseModel.Meta``.

    Attributes:
        sequence: The primary key, generated by the database - the order the relay delivers in.
            Events of one row are written under that row's lock, so their order is the order of
            their commits whatever the clocks of the hosts.
        id: The event's own id - the key a receiver deduplicates on.
        ordering_key: Events of one key are delivered strictly in order; None for none.
        headers: Metadata of the event besides its payload - a trace context, the author of a
            change - carried into the headers of a Kafka, RabbitMQ or HTTP message.
        next_attempt_at: When a failed event is tried again; None for at once.
        lease_until, leased_by: The relay delivering the event and until when it may.
        lease_token: The claim identity protecting attempt metadata and failures during lease handoff.
        dead_lettered_at: When the event ran out of attempts - it is no longer delivered.
    """

    sequence = fields.BigIntField(primary_key=True)
    id = fields.UUIDField(default=Uuid7.new, unique=True, version=7)
    topic = fields.CharField(max_length=OUTBOX_KEY_MAX_LENGTH)
    payload = JSONTextField(encoder=OutboxJsonEncoding.dumps)
    headers = JSONTextField(encoder=OutboxJsonEncoding.dumps, default=dict)
    ordering_key = fields.CharField(max_length=OUTBOX_KEY_MAX_LENGTH, null=True)
    # Set only by enqueue(idempotency_key=...). Unique, but NULLs never conflict with each other, so
    # rows enqueued without a key are unaffected.
    idempotency_key = fields.CharField(max_length=OUTBOX_KEY_MAX_LENGTH, null=True, unique=True)
    created_at = fields.DatetimeField(auto_now_add=True)
    attempts = fields.IntField(default=0)
    last_error = fields.TextField(null=True)
    next_attempt_at = fields.DatetimeField(null=True)
    lease_until = fields.DatetimeField(null=True)
    leased_by = fields.CharField(max_length=OUTBOX_KEY_MAX_LENGTH, null=True)
    lease_token = fields.UUIDField(null=True)
    published_at = fields.DatetimeField(null=True)
    dead_lettered_at = fields.DatetimeField(null=True)

    class Meta:
        abstract = True
        indexes = (
            Index(fields=("topic", "sequence")),
            # The relay's queue - the rows still to deliver, in order.
            PartialIndex(fields=("sequence",), condition=Q(published_at__isnull=True, dead_lettered_at__isnull=True)),
            # An earlier undelivered event of the same ordering key holds a row back.
            PartialIndex(fields=("ordering_key", "sequence"), condition=Q(published_at__isnull=True)),
            PartialIndex(fields=("published_at",), condition=Q(published_at__isnull=False)),
            PartialIndex(fields=("dead_lettered_at",), condition=Q(dead_lettered_at__isnull=False)),
        )

    @classmethod
    def get_wakeup(cls) -> OutboxWakeup | None:
        """The wakeup the events of the model signal - ``Meta.outbox_wakeup``.

        Returns:
            The wakeup, None when the model declares none.
        """
        return OutboxWakeups.get_wakeup(cls)

    @classmethod
    async def enqueue(
        cls,
        topic: str,
        payload: Any,
        *,
        using: str | DatabaseClient | None = None,
        idempotency_key: str | None = None,
        ordering_key: str | None = None,
        headers: Mapping[str, Any] | None = None,
        extra_field_values: Mapping[str, Any] | None = None,
        wakeup: OutboxWakeup | None = None,
    ) -> Self:
        """Writes an outbox event - atomic with the caller's own write when called inside
        ``Transactions.atomic()`` on the same connection. Once the transaction commits (at once
        outside a transaction) the wakeup signals the relays.

        Args:
            topic: The event's topic - a delivery routes on it.
            payload: The event's payload - JSON values, or values ``OutboxJsonEncoding`` writes.
            using: The connection to write on instead of the model's.
            idempotency_key: At most one stored event exists per key: while it is retained, it is
                returned unchanged instead of writing a new one - no error, no duplicate. Written as
                ``INSERT ... ON CONFLICT (idempotency_key) DO NOTHING`` and a ``SELECT``, so a key
                conflict never aborts an enclosing transaction. After cleanup removes the event, the
                same key may create a new one; retention determines the deduplication window.
            ordering_key: Events of one key are delivered strictly in the order they were written.
            headers: Metadata of the event besides its payload.
            extra_field_values: Values of the columns a subclass declares on top of
                ``OutboxEvent``'s own.
            wakeup: The wakeup to signal instead of the model's ``Meta.outbox_wakeup``.

        Returns:
            The event - the one already stored under ``idempotency_key`` when there is one.

        Raises:
            ValidationError: ``topic``, ``idempotency_key`` or ``ordering_key`` isn't text of 1 to
                255 characters, ``headers`` isn't a mapping of text keys, or ``extra_field_values``
                sets a field ``enqueue()`` or ``OutboxRelay`` sets itself.
            ValidationError: The payload or the headers hold a value without a JSON form here
                (``OutboxJsonEncoding``).
            IntegrityError: ``idempotency_key`` conflicts with an event this call can't see - another
                tenant's, or one committed after this transaction's snapshot; or the event violates
                another unique constraint.
            ConfigurationError: ``using`` wasn't given, the model's connection has no open
                transaction and another connection has one - the event would commit on its own
                instead of with that transaction's write. Pass ``using=`` if this is intended. Or the
                wakeup can't signal on the connection's database (``ListenNotifyWakeup`` without
                listen/notify) - refused before the event is written.
        """
        return await OutboxEnqueue.enqueue(
            cls,
            topic,
            payload,
            using=using,
            idempotency_key=idempotency_key,
            ordering_key=ordering_key,
            headers=headers,
            extra_field_values=extra_field_values,
            wakeup=wakeup,
        )

    @classmethod
    async def enqueue_many(
        cls,
        messages: Iterable[OutboxMessage],
        *,
        using: str | DatabaseClient | None = None,
        wakeup: OutboxWakeup | None = None,
    ) -> list[Self]:
        """Writes several outbox events as ``enqueue()`` writes one, in one transaction - an ``INSERT`` per
        run of consecutive events alike (with an idempotency key or without, of one tenant named), the
        events in the order given, so the ones of an ordering key are delivered in that order; one
        signal of the wakeup for all of them.

        Args:
            messages: The events - ``OutboxMessage(topic, payload, idempotency_key=..., ...)``.
            using: The connection to write on instead of the model's.
            wakeup: The wakeup to signal instead of the model's ``Meta.outbox_wakeup``.

        Returns:
            The events in the order given - for an idempotency key already stored (or given twice), the
            event stored under it.

        Raises:
            ValidationError: A message's arguments, as ``enqueue()`` refuses them.
            IntegrityError: An idempotency key conflicts with an event this call can't see.
            ConfigurationError: As ``enqueue()``.
        """
        return await OutboxEnqueue.enqueue_many(cls, messages, using=using, wakeup=wakeup)

    @classmethod
    def get_enqueue_run_key(cls, message: OutboxMessage) -> tuple[bool, Any]:
        """What the events of one ``INSERT`` of ``enqueue_many()`` share - an idempotency key or none, and
        the tenant a message names where no tenant scope is active.

        Args:
            message: The message.

        Returns:
            The key.
        """
        return OutboxEnqueue.get_enqueue_run_key(cls, message)

    @classmethod
    async def write_enqueue_run(
        cls, messages: Sequence[OutboxMessage], has_idempotency_key: bool, connection: DatabaseClient
    ) -> tuple[list[Self], set[str]]:
        """Writes one run of ``enqueue_many()`` - one ``INSERT``, under the tenant its messages name when
        no tenant scope is active.

        Args:
            messages: The messages of the run.
            has_idempotency_key: Whether they have idempotency keys.
            connection: The connection, in the call's transaction.

        Returns:
            The events of the messages, in their order, and the topics of the ones inserted.
        """
        return await OutboxEnqueue.write_enqueue_run(cls, messages, has_idempotency_key, connection)

    @classmethod
    async def write_enqueue_run_in_scope(
        cls, messages: Sequence[OutboxMessage], has_idempotency_key: bool, connection: DatabaseClient
    ) -> tuple[list[Self], set[str]]:
        """Writes one run of ``enqueue_many()`` in the tenant scope it runs under.

        Args:
            messages: The messages of the run.
            has_idempotency_key: Whether they have idempotency keys.
            connection: The connection, in the call's transaction.

        Returns:
            The events of the messages, in their order, and the topics of the ones inserted.

        Raises:
            IntegrityError: An idempotency key is taken by an event not visible to this call.
        """
        return await OutboxEnqueue.write_enqueue_run_in_scope(cls, messages, has_idempotency_key, connection)

    @classmethod
    def get_write_connection(cls, using: str | DatabaseClient | None, method_name: str = "enqueue") -> DatabaseClient:
        """The connection an event is written on.

        Args:
            using: The connection asked for, None for the model's.
            method_name: The method writing - named by the error.

        Returns:
            The connection.

        Raises:
            ConfigurationError: ``using`` wasn't given, the model's connection has no open
                transaction and another connection has one.
        """
        return OutboxEnqueue.get_write_connection(cls, using, method_name)

    @classmethod
    def raise_if_wakeup_unsupported(cls, connection: DatabaseClient, wakeup: OutboxWakeup | None = None) -> None:
        """Refuses writing events the wakeup can't signal on ``connection`` - before they are written, not
        after they committed.

        Args:
            connection: The connection the events are written on.
            wakeup: The wakeup, the model's ``Meta.outbox_wakeup`` when None.

        Raises:
            ConfigurationError: The wakeup can't signal on the connection's database.
        """
        return OutboxWakeups.raise_if_wakeup_unsupported(cls, connection, wakeup)

    @classmethod
    async def signal_wakeup(
        cls, connection: DatabaseClient, topics: Iterable[str], wakeup: OutboxWakeup | None = None
    ) -> None:
        """Signals the relays that events of ``topics`` were written - once ``connection``'s transaction
        commits, at once outside a transaction.

        Args:
            connection: The connection the events were written on.
            topics: Their topics.
            wakeup: The wakeup, the model's ``Meta.outbox_wakeup`` when None.
        """
        return await OutboxWakeups.signal_wakeup(cls, connection, topics, wakeup)

    @classmethod
    def validate_enqueue_options(
        cls,
        topic: Any,
        idempotency_key: Any,
        ordering_key: Any,
        headers: Mapping[str, Any] | None,
        extra_field_values: Mapping[str, Any] | None,
    ) -> None:
        """Checks ``enqueue()``'s arguments - their text lengths are the fields' own checks.

        Raises:
            ValidationError: ``topic``, ``idempotency_key`` or ``ordering_key`` is empty text,
                ``extra_field_values`` sets a field of an argument or of the relay, or ``headers`` isn't
                a mapping of non-empty text names.
        """
        return OutboxValidation.validate_enqueue_options(
            cls, topic, idempotency_key, ordering_key, headers, extra_field_values
        )

    @staticmethod
    def validate_keys(topic: Any, idempotency_key: Any, ordering_key: Any) -> None:
        """Checks an event's topic and keys aren't empty text - their lengths are the fields' own checks.

        Args:
            topic: The topic.
            idempotency_key: The idempotency key, None for none.
            ordering_key: The ordering key, None for none.

        Raises:
            ValidationError: One of them is empty text.
        """
        return OutboxValidation.validate_keys(topic, idempotency_key, ordering_key)

    @staticmethod
    def validate_headers(headers: Mapping[str, Any] | None) -> None:
        """Checks an event's headers - a delivery sends each by its name.

        Args:
            headers: The headers, None for none.

        Raises:
            ValidationError: They aren't a mapping of non-empty text names.
        """
        return OutboxValidation.validate_headers(headers)

    @classmethod
    async def insert_or_get_by_idempotency_key(
        cls,
        topic: str,
        payload: Any,
        idempotency_key: str,
        ordering_key: str | None,
        headers: dict[str, Any],
        write_connection: DatabaseClient,
        field_values: Mapping[str, Any],
    ) -> tuple[Self, bool]:
        """Inserts an event with ``idempotency_key`` unless one already exists, then reads it back.

        Args:
            topic: The topic of a new event.
            payload: The payload of a new event.
            idempotency_key: The unique key.
            ordering_key: The ordering key of a new event.
            headers: The headers of a new event.
            write_connection: The connection - possibly a transaction - both statements run on.
            field_values: Subclass column values of a new event.

        Returns:
            The event stored under the key, and whether this call inserted it.

        Raises:
            IntegrityError: The key is taken by an event not visible to this call.
            ConfigurationError: ``Meta.tenant_field`` is set, ``field_values`` names no tenant and
                no tenant scope is active; or the named tenant conflicts with the active scope.
        """
        return await OutboxIdempotency.insert_or_get_by_idempotency_key(
            cls, topic, payload, idempotency_key, ordering_key, headers, write_connection, field_values
        )

    @classmethod
    def get_idempotency_conflict_field_names(cls) -> list[str]:
        """The unique field set ``idempotency_key`` conflicts on.

        Returns:
            ``["idempotency_key"]`` for a unique column, otherwise the fields of the first
            unconditional ``UniqueConstraint`` that includes it.

        Raises:
            ConfigurationError: No unique constraint covers ``idempotency_key``.
        """
        return OutboxIdempotency.get_idempotency_conflict_field_names(cls)

    def __repr__(self) -> str:
        return f"<{type(self).__name__} id={self.id} topic={self.topic!r} published_at={self.published_at!r}>"
