from __future__ import annotations

import asyncio
import datetime
import time
import uuid
from typing import Any

from orm_benchmark.constants import (
    CLICKHOUSE_DAY_COUNT,
    CLICKHOUSE_EVENT_TYPES,
    CLICKHOUSE_FIRST_DAY,
    CLICKHOUSE_INSERTED_SITE,
    CLICKHOUSE_SITE_COUNT,
    CLICKHOUSE_USER_COUNT,
    LOAD_CONCURRENCY,
    LOAD_OPERATIONS,
)
from orm_benchmark.definitions.target import Target
from orm_benchmark.measuring.load_test import LoadTest
from orm_benchmark.measuring.timing import Timing
from orm_benchmark.measuring.workload import Workload


class ClickhouseSuite:
    """The scenarios on ClickHouse: a table of events, read by aggregates and point reads and written in
    bulk and by mutations. A participant's suite writes each operation the way its library's
    documentation writes it; this class runs them, seeds the table and runs the load test, so every
    participant does the same work. A mutation finishes before its call returns, on every participant.
    """

    def __init__(self, target: Target, database: Any) -> None:
        """
        Args:
            target: The target.
            database: The run's ``ClickhouseDatabase``.
        """
        self.target = target
        self.database = database

    # --- What a participant writes -----------------------------------------------------------------

    def load(self) -> None:
        """Imports the library and declares its event model - before the start is timed, as an
        application has done by the time it connects."""
        raise NotImplementedError()

    async def connect(self) -> None:
        """Opens the library's connection to the run's database and runs its first query."""
        raise NotImplementedError()

    async def close(self) -> None:
        raise NotImplementedError()

    async def create_table(self) -> None:
        """Creates the ``event`` table: ``id`` (UUID, the sort key), ``site``, ``user_id``, ``amount``
        (a float), ``happened_at`` (a moment) and ``event_type``."""
        raise NotImplementedError()

    async def insert(self, rows: list[dict[str, Any]]) -> None:
        """Inserts the rows in one statement."""
        raise NotImplementedError()

    async def count_filter(self) -> None:
        """``count()`` of the ``buy`` events with an amount over 50."""
        raise NotImplementedError()

    async def group_sum(self) -> None:
        """Per site: the sum and the average of the amount."""
        raise NotImplementedError()

    async def top_n(self) -> None:
        """The 10 users with the largest sum of the amount."""
        raise NotImplementedError()

    async def by_day(self) -> None:
        """The events per day of ``happened_at``."""
        raise NotImplementedError()

    async def distinct_count(self) -> None:
        """The number of distinct users."""
        raise NotImplementedError()

    async def page_values(self) -> None:
        """``id``, ``site`` and ``amount`` of 100 events by ``id``, from the 1000th."""
        raise NotImplementedError()

    async def get_by_key(self, key: uuid.UUID) -> None:
        """One event by its ``id``."""
        raise NotImplementedError()

    async def update_mutation(self) -> None:
        """The amount of the ``share`` events set to 0."""
        raise NotImplementedError()

    async def delete_mutation(self, site: str) -> None:
        """The events of a site deleted."""
        raise NotImplementedError()

    async def count_day(self, day: datetime.datetime) -> None:
        """The events of one day per event type - the load test's aggregate."""
        raise NotImplementedError()

    # --- The run ------------------------------------------------------------------------------------

    @staticmethod
    def get_seed_sql(rows: int) -> str:
        """The ``INSERT ... SELECT`` the server fills the table with - the same rows for every
        participant, generated by the server rather than sent."""
        event_types = ", ".join(f"'{event_type}'" for event_type in CLICKHOUSE_EVENT_TYPES)
        seconds = CLICKHOUSE_DAY_COUNT * 86400
        return (
            "INSERT INTO event (id, site, user_id, amount, happened_at, event_type) "
            f"SELECT generateUUIDv4(number), concat('site', toString(number % {CLICKHOUSE_SITE_COUNT})), "
            f"number % {CLICKHOUSE_USER_COUNT}, (number % 1000) / 10, "
            f"toDateTime64('{CLICKHOUSE_FIRST_DAY} 00:00:00', 6, 'UTC') + toIntervalSecond(number % {seconds}), "
            f"[{event_types}][number % {len(CLICKHOUSE_EVENT_TYPES)} + 1] FROM numbers({rows})"
        )

    @staticmethod
    def get_first_moment() -> datetime.datetime:
        return datetime.datetime.fromisoformat(CLICKHOUSE_FIRST_DAY).replace(tzinfo=datetime.UTC)

    @classmethod
    def make_rows(cls, count: int) -> list[dict[str, Any]]:
        """The rows the timed insert writes."""
        first_moment = cls.get_first_moment()
        return [
            {
                "id": uuid.uuid4(),
                "site": CLICKHOUSE_INSERTED_SITE,
                "user_id": index % CLICKHOUSE_USER_COUNT,
                "amount": (index % 1000) / 10,
                "happened_at": first_moment + datetime.timedelta(seconds=index),
                "event_type": CLICKHOUSE_EVENT_TYPES[index % len(CLICKHOUSE_EVENT_TYPES)],
            }
            for index in range(count)
        ]

    async def run(self, rows: int) -> dict[str, float | None]:
        """Runs every scenario and the load test.

        Args:
            rows: The widget table size of the run's ``--size`` - the event counts follow from it.

        Returns:
            Each scenario's time in milliseconds, and the load test's figures.
        """
        counts = Workload.get_counts(rows)
        self.load()
        start = time.perf_counter()
        await self.connect()
        cold_start = (time.perf_counter() - start) * 1000
        try:
            await self.create_table()
            await self.database.run(self.get_seed_sql(counts["events"]))
            results = await self.run_scenarios(counts)
            results["cold_start"] = cold_start
            results.update(await self.run_load_test())
        finally:
            await self.close()
        return results

    async def get_keys(self, count: int) -> list[uuid.UUID]:
        response = await self.database.run(f"SELECT id FROM event ORDER BY id LIMIT {count}")
        return [uuid.UUID(line) for line in response.split()]

    async def run_scenarios(self, counts: dict[str, int]) -> dict[str, float | None]:
        best = Timing.get_best
        results: dict[str, float | None] = {}
        inserted_rows = self.make_rows(counts["insert_rows"])

        async def clear_inserted() -> None:
            await self.database.run(f"DELETE FROM event WHERE site = '{CLICKHOUSE_INSERTED_SITE}'")

        async def bulk_insert() -> None:
            await self.insert(inserted_rows)

        results["bulk_insert"] = await best(bulk_insert, 3, clear_inserted)
        await clear_inserted()
        results["count_filter"] = await best(self.count_filter, 5)
        results["group_sum"] = await best(self.group_sum, 5)
        results["top_n"] = await best(self.top_n, 5)
        results["by_day"] = await best(self.by_day, 5)
        results["distinct_count"] = await best(self.distinct_count, 5)
        results["page_values"] = await best(self.page_values, 5)
        keys = await self.get_keys(counts["batch"])

        async def get_by_key() -> None:
            for key in keys:
                await self.get_by_key(key)

        results["get_by_key"] = await best(get_by_key, 3)

        async def concurrent_reads() -> None:
            await asyncio.gather(*[self.get_by_key(key) for key in keys])

        results["concurrent_reads"] = await best(concurrent_reads, 3)
        results["mutation_update"] = await best(self.update_mutation, 3)

        async def mutation_delete() -> None:
            await self.delete_mutation("site7")

        results["mutation_delete"] = await best(mutation_delete, 1)
        return results

    async def run_load_test(self) -> dict[str, float]:
        keys = await self.get_keys(200)
        first_moment = self.get_first_moment()

        async def operation(index: int) -> None:
            if index % 5 < 4:
                await self.get_by_key(keys[index % len(keys)])
            else:
                await self.count_day(first_moment + datetime.timedelta(days=index % CLICKHOUSE_DAY_COUNT))

        return await LoadTest.run("load_test", operation, LOAD_CONCURRENCY, LOAD_OPERATIONS)
